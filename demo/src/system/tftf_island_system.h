bool tftf_island_biome_index_at_cell(
    i32 cell_x, i32 cell_y, u32 *out_index);
bool tftf_island_biome_index_at(
    Vec3 world_position, u32 *out_index);

//@system components=LDK_COMPONENT_TYPE_CAMERA initialize=tftf_island_system_initialize update=tftf_island_system_update terminate=tftf_island_system_terminate flags=LDK_SYSTEM_FLAG_ENABLED|LDK_SYSTEM_FLAG_RUN_WHEN_PAUSED
typedef struct TFTFIslandSystem
{
  //@begin_group "Island Generation"
  u32 seed;
  /** Square map side, in cells. */
  u32 map_size;
  /** Target land coverage passed to the geography generator (1..80%). */
  //@inspect slider min=1 max=80
  float land_coverage_percent;
  /** Minimum water gap between the main island and satellite islands,
   * measured in terrain cells. */
  //@inspect min=0
  float min_island_gap_tiles;
  /** Maximum water gap between the main island and satellite islands,
   * measured in terrain cells. Must be >= min_island_gap_tiles. */
  //@inspect min=0
  float max_island_gap_tiles;
  /** Normalized sea level. Match WaterSystem water_level / TerrainSystem
   * height_scale. */
  //@inspect slider min=0 max=1
  float sea_level;
  /** Normalized elevation per positive height unit from the generator. */
  float land_height_scale;
  /** Normalized depth per negative height unit from the generator. */
  float underwater_depth_scale;
  //@end_group

  //@begin_group "Biomes"
  /** Each generated surface must resolve to a configured biome. */
  //@inspect element_type=IslandBiomeDesc initializer=tftf_island_biome_initialize max_count=255
  XArray_IslandBiomeDesc *biomes;
  //@end_group

  //@begin_group "Island Rendering"
  u32 radius;
  float cell_size;
  float elevation;
  float forward_offset;
  LDKAssetMaterial material;
  //@end_group

  //@begin_group "Runtime"
  //@inspect runtime
  i32 center_x;
  //@inspect runtime
  i32 center_y;
  //@inspect runtime
  u32 cached_radius;
  //@inspect runtime
  float cached_cell_size;
  //@inspect runtime
  float cached_elevation;
  //@inspect runtime
  u32 map_revision;
  //@inspect runtime
  u32 active_tile_count;
  //@inspect runtime
  u32 tiles_added;
  //@inspect runtime
  u32 tiles_removed;
  //@inspect runtime
  u32 mesh_update_count;
  //@inspect runtime
  bool mesh_dirty;
  //@inspect runtime
  bool has_geometry;
  //@inspect runtime
  bool map_loaded_from_cache;
  //@inspect runtime
  LDKResourceMesh mesh;
  //@end_group
} TFTFIslandSystem;

#endif // TFTF_ISLAND_SYSTEM_H
